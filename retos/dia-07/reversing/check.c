#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende d[n-1-i]  (arreglo guardado al reves) o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x7d, 0x38, 0x75, 0x6a, 0x37, 0x5f, 0x67, 0x6e, 0x69, 0x73, 0x72, 0x65, 0x76, 0x65, 0x72, 0x5f, 0x37, 0x30, 0x64, 0x7b, 0x47, 0x41, 0x4c, 0x46 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar(d[n-1-i]);
    }
    putchar('\n');
    return 0;
}
