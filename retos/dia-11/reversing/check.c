#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende ((d[i] ^ (i & 0xff)) + 0xb3) & 0xff o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x93, 0x98, 0x8c, 0x97, 0xcc, 0xb4, 0x78, 0x79, 0xa4, 0xb6, 0xb8, 0xc8, 0xbe, 0xb2, 0xce, 0xb9, 0xab, 0xa5, 0xbe, 0xd2, 0xd6, 0xaa, 0xa1, 0xdd };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)(((d[i] ^ (i & 0xff)) + 0xb3)));
    }
    putchar('\n');
    return 0;
}
