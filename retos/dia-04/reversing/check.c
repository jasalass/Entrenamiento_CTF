#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende (~(d[i] ^ 0x84)) & 0xff o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x3d, 0x37, 0x3a, 0x3c, 0x00, 0x1f, 0x4b, 0x4f, 0x24, 0x09, 0x1e, 0x0d, 0x1e, 0x09, 0x08, 0x12, 0x15, 0x1c, 0x24, 0x13, 0x4c, 0x1d, 0x4f, 0x06 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)(~(d[i] ^ 0x84)));
    }
    putchar('\n');
    return 0;
}
