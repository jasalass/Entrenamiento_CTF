#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende ((d[i] ^ 0xef) - 30) & 0xff o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x8b, 0x85, 0xb0, 0x8a, 0x76, 0x6d, 0xa0, 0xba, 0x92, 0x7f, 0x6c, 0x7b, 0x6c, 0x7f, 0x7e, 0x68, 0x63, 0x6a, 0x92, 0xbc, 0x6b, 0x6a, 0x66, 0x74 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)((d[i] ^ 0xef) - 30));
    }
    putchar('\n');
    return 0;
}
