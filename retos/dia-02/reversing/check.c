#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende (d[i] - 0x2b) & 0xff o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x71, 0x77, 0x6c, 0x72, 0xa6, 0x8f, 0x5b, 0x5d, 0x8a, 0x9d, 0x90, 0xa1, 0x90, 0x9d, 0x9e, 0x94, 0x99, 0x92, 0x8a, 0x8d, 0x64, 0x99, 0x63, 0xa8 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)(d[i] - 0x2b));
    }
    putchar('\n');
    return 0;
}
