#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende (d[i] - 0x7c - i) & 0xff o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0xc2, 0xc9, 0xbf, 0xc6, 0xfb, 0xe5, 0xb2, 0xbc, 0xe3, 0xf7, 0xeb, 0xfd, 0xed, 0xfb, 0xfd, 0xf4, 0xfa, 0xf4, 0xed, 0xfa, 0x0a, 0x08, 0x02, 0x10 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)(d[i] - 0x7c - i));
    }
    putchar('\n');
    return 0;
}
