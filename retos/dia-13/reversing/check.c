#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende (d[i] ^ 0xd0) - (i & 0xff)  [mod 256] o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x96, 0x9d, 0x93, 0x9a, 0xaf, 0xb9, 0xe7, 0xea, 0xb7, 0xab, 0xbf, 0x51, 0xa1, 0xaf, 0x51, 0xa8, 0xae, 0xa8, 0xa1, 0x95, 0x9b, 0x52, 0x54, 0x44 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)((d[i] ^ 0xd0) - (i & 0xff)));
    }
    putchar('\n');
    return 0;
}
