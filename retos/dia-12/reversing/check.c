#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende d[i] ^ ((0x15 + 3*i) & 0xff) o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x53, 0x54, 0x5a, 0x59, 0x5a, 0x40, 0x16, 0x18, 0x72, 0x42, 0x56, 0x40, 0x5c, 0x4e, 0x4c, 0x2b, 0x2b, 0x2f, 0x14, 0x76, 0x66, 0x22, 0x3f, 0x27 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)(d[i] ^ ((0x15 + 3*i) & 0xff)));
    }
    putchar('\n');
    return 0;
}
