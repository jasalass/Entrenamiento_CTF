#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende ((d[i] + 76) & 0xff) ^ 0xed o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x5f, 0x55, 0x60, 0x5e, 0x4a, 0x3d, 0x90, 0x88, 0x66, 0x53, 0x3c, 0x4f, 0x3c, 0x53, 0x52, 0x38, 0x37, 0x3e, 0x66, 0x4f, 0x3f, 0x4c, 0x49, 0x44 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)((d[i] + 76) ^ 0xed));
    }
    putchar('\n');
    return 0;
}
