#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende ((d[i] ^ ((2*i) & 0xff)) + 0x10) & 0xff o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x36, 0x3e, 0x35, 0x31, 0x63, 0x5e, 0x2d, 0x2b, 0x5f, 0x70, 0x41, 0x70, 0x4d, 0x78, 0x7f, 0x47, 0x7e, 0x75, 0x6b, 0x7a, 0x4d, 0x4b, 0x0f, 0x43 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)((d[i] ^ ((2*i) & 0xff)) + 0x10));
    }
    putchar('\n');
    return 0;
}
