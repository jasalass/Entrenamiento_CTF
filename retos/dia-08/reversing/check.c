#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende d[i] ^ 0x4c ^ (i & 0xff) o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x0a, 0x01, 0x0f, 0x08, 0x33, 0x2d, 0x7a, 0x73, 0x1b, 0x37, 0x23, 0x31, 0x25, 0x33, 0x31, 0x2a, 0x32, 0x3a, 0x01, 0x25, 0x6c, 0x6c, 0x34, 0x26 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)(d[i] ^ 0x4c ^ (i & 0xff)));
    }
    putchar('\n');
    return 0;
}
