#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende d[i] ^ 0x36 o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x70, 0x7a, 0x77, 0x71, 0x4d, 0x52, 0x06, 0x07, 0x69, 0x44, 0x53, 0x40, 0x53, 0x44, 0x45, 0x5f, 0x58, 0x51, 0x69, 0x5f, 0x5a, 0x57, 0x00, 0x4b };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar(d[i] ^ 0x36);
    }
    putchar('\n');
    return 0;
}
