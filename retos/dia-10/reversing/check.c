#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende ((d[i] + (i & 0xff)) & 0xff) ^ 0xd7 o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x91, 0x9a, 0x94, 0x8d, 0xa8, 0xae, 0xe0, 0xe0, 0x80, 0x9c, 0xa8, 0x96, 0xa6, 0x98, 0x96, 0xaf, 0xa9, 0x9f, 0x76, 0x8d, 0xa2, 0xce, 0x8e, 0x93 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)(((d[i] + (i & 0xff)) & 0xff) ^ 0xd7));
    }
    putchar('\n');
    return 0;
}
