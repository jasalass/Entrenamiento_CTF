#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende (d[i] + 0xdb) & 0xff o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0x6b, 0x71, 0x66, 0x6c, 0xa0, 0x89, 0x55, 0x58, 0x84, 0x97, 0x8a, 0x9b, 0x8a, 0x97, 0x98, 0x8e, 0x93, 0x8c, 0x84, 0x96, 0x8c, 0x5a, 0x92, 0xa2 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)(d[i] + 0xdb));
    }
    putchar('\n');
    return 0;
}
