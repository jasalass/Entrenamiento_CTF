#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende ((d[i] ^ 0xcc) + 64) & 0xff o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0xca, 0xc0, 0xcd, 0xcb, 0xf7, 0xe8, 0x3d, 0x34, 0xd3, 0xfe, 0xe9, 0xfa, 0xe9, 0xfe, 0xff, 0xe5, 0xe2, 0xeb, 0xd3, 0xe3, 0x3b, 0x3f, 0xf4, 0xf1 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)((d[i] ^ 0xcc) + 64));
    }
    putchar('\n');
    return 0;
}
