#include <stdio.h>
/* Imprime la flag aplicando la inversa. Entiende ((d[i] - 27) & 0xff) ^ 0x85 o ejecuta el binario. */
int main(void){
    unsigned char d[]={ 0xde, 0xe4, 0xdf, 0xdd, 0x19, 0xfc, 0xcf, 0xce, 0xf5, 0x12, 0xfb, 0x0e, 0xfb, 0x12, 0x11, 0x07, 0x06, 0xfd, 0xf5, 0x12, 0xcd, 0xd1, 0x0b, 0x13 };
    int n=sizeof(d);
    for(int i=0;i<n;i++){
        putchar((unsigned char)((d[i] - 27) ^ 0x85));
    }
    putchar('\n');
    return 0;
}
